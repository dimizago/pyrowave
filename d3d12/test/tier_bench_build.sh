#!/bin/sh
# Regenerates tier_bench_dxil.h from tier_bench.hlsl (WSL, Windows dxc).
set -e
cd "$(dirname "$0")"
DXC=${PYROWAVE_DXC:-"/mnt/c/Program Files (x86)/Windows Kits/10/bin/10.0.26100.0/x64/dxc.exe"}
out=tier_bench_dxil.h
printf '// Generated by tier_bench_build.sh from tier_bench.hlsl -- do not edit.\n#pragma once\n\n' > $out
for e in alu_latency alu_throughput read_bandwidth typed_store empty_dispatch store_r16_rows store_r16_idwt \
		store_rgba16_rows store_rg16_rows store_raw_dword store_raw_dword4 load_gather_r16 load_rgba16 \
		pyr_r16_lane4x4 pyr_r16_tile8x8 pyr_rgba16_tile pyr_raw_tiled_x2 pyr_raw_tiled_x4 pyr_raw_rows_x2; do
	"$DXC" -nologo -T cs_6_0 -E $e -O3 -Qstrip_debug -Qstrip_reflect tier_bench.hlsl -Fh tmp_$e.h -Vn tier_bench_$e
	tr -d '\r' < tmp_$e.h | sed '/^#if 0/,/^#endif/d' >> $out
	rm tmp_$e.h
done
